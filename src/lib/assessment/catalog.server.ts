/** Retain database overrides and extra records while filling missing canonical keys. */
export function completeCatalog<T extends { key: string }>(canonical: T[], stored: T[]): T[] {
  const records = new Map(canonical.map((row) => [row.key, row]));
  for (const row of stored) records.set(row.key, row);
  return [...records.values()];
}
