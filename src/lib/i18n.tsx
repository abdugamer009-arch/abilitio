// ---------- Context ----------
type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Dict;
  tQuestion: (id: string) => QT | undefined;
  tCareer: (name: string) => { name: string; reason: string };
  tTrait: (name: string) => string;
  tIqLevel: (level: string) => string;
};

const LangContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (saved && (saved === "en" || saved === "ru" || saved === "uz")) {
        setLangState(saved);
      }
    } catch {
      /* ignore */
    }
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
    if (typeof document !== "undefined") document.documentElement.lang = l;
  };

  const value: Ctx = {
    lang,
    setLang,
    t: translations[lang] as Dict,
    tQuestion: (id) => QUESTIONS[lang][id] ?? QUESTIONS.en[id],
    tCareer: (name) => CAREERS_T[lang][name] ?? CAREERS_T.en[name] ?? { name, reason: "" },
    tTrait: (name) => (translations[lang].traits as Record<string, string>)[name] ?? name,
    tIqLevel: (level) => (translations[lang].iqLevels as Record<string, string>)[level] ?? level,
  };

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useI18n must be used inside LanguageProvider");
  return ctx;
}

export function useT() {
  return useI18n().t;
}

/** Provider-free dictionary for surfaces that can render outside
 *  LanguageProvider (the root error / not-found pages replace the component
 *  tree that mounts the provider). Reads the stored language directly;
 *  falls back to English during SSR. */
export function getStaticDict(): Dict {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && (saved === "ru" || saved === "uz")) return translations[saved] as unknown as Dict;
  } catch {
    /* SSR or blocked storage — English */
  }
  return translations.en;
}
